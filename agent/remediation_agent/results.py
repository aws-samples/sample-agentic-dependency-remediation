"""Where a run's outputs go.

Every run produces the same three artifacts, whatever the outcome:

* result.json  machine-readable outcome for CI and automation
* fix.patch    the verified change, for `git apply` (only when a fix was found)
* report.md    human-readable report, suitable as a merge request description

In AWS they are written to s3://<bucket>/results/<project>/<run-id>/ and an
EventBridge "Remediation Completed" event is published. Locally they are
written to a folder.
"""

from __future__ import annotations

import json
import logging
from pathlib import Path

log = logging.getLogger(__name__)

EVENT_SOURCE = "dependency.remediation"
EVENT_DETAIL_TYPE = "Remediation Completed"


class LocalResultSink:
    def __init__(self, folder: Path):
        self.folder = folder

    def write(self, result: dict, patch: str | None, report: str) -> dict:
        self.folder.mkdir(parents=True, exist_ok=True)
        (self.folder / "result.json").write_text(json.dumps(result, indent=2))
        (self.folder / "report.md").write_text(report)
        if patch:
            (self.folder / "fix.patch").write_text(patch)
        return {"location": str(self.folder)}


def notification_text(result: dict) -> tuple[str, str]:
    """Plain-text email subject and body for a finished run."""
    from .report import STATUS_TEXT, advisory_summary

    status = result.get("status", "UNKNOWN")
    subject = f"Dependency remediation: {result.get('project', '?')} - {status}"[:100]
    lines = [
        f"Project:  {result.get('project', '?')}",
        f"Status:   {status}. {STATUS_TEXT.get(status, '')}".rstrip(),
        f"Run ID:   {result.get('run_id', '?')}",
        f"Builds:   {result.get('build_attempts', 0)}",
    ]
    if result.get("reason"):
        lines.append(f"Reason:   {result['reason']}")
    lines += ["", "Upgraded:"]
    lines += [f"  - {f['package']} {f['from']} -> {f['to']} ({advisory_summary(f['advisories'])})" for f in result.get("fixed", [])] or ["  (none)"]
    lines += ["", "Not fixed:"]
    lines += [f"  - {s['package']} {s['from']}: {s.get('note') or s['status']}" for s in result.get("skipped", [])] or ["  (none)"]
    artifacts = result.get("artifacts", {})
    lines += ["", "Files:"] + [f"  {name}: {uri}" for name, uri in artifacts.items()]
    if "patch" in artifacts:
        lines += ["", "Get and apply the patch:", f"  aws s3 cp {artifacts['patch']} . && git apply --index fix.patch"]
    lines += ["", "Generated by an AI agent. Review the change as you would any other contribution."]
    return subject, "\n".join(lines)


class S3ResultSink:
    def __init__(self, bucket: str, prefix: str, region: str, event_bus: str | None = "default", topic_arn: str | None = None):
        import boto3

        self.s3 = boto3.client("s3", region_name=region)
        self.events = boto3.client("events", region_name=region) if event_bus else None
        self.sns = boto3.client("sns", region_name=region) if topic_arn else None
        self.bucket = bucket
        self.prefix = prefix.rstrip("/") + "/"
        self.event_bus = event_bus
        self.topic_arn = topic_arn

    def _put(self, name: str, body: str, content_type: str) -> str:
        key = self.prefix + name
        self.s3.put_object(Bucket=self.bucket, Key=key, Body=body.encode(), ContentType=content_type, ServerSideEncryption="aws:kms")
        return f"s3://{self.bucket}/{key}"

    def write(self, result: dict, patch: str | None, report: str) -> dict:
        locations = {"report": self._put("report.md", report, "text/markdown")}
        if patch:
            locations["patch"] = self._put("fix.patch", patch, "text/x-diff")
        result = {**result, "artifacts": locations}
        # result.json is written last: its presence tells clients the run is finished.
        locations["result"] = self._put("result.json", json.dumps(result, indent=2), "application/json")
        if self.events:
            try:
                self.events.put_events(
                    Entries=[
                        {
                            "Source": EVENT_SOURCE,
                            "DetailType": EVENT_DETAIL_TYPE,
                            "EventBusName": self.event_bus,
                            "Detail": json.dumps({k: result[k] for k in ("run_id", "project", "status", "fixed", "skipped", "artifacts") if k in result}),
                        }
                    ]
                )
            except Exception:
                log.exception("Failed to publish the completion event")
        if self.sns:
            try:
                subject, body = notification_text({**result, "artifacts": locations})
                self.sns.publish(TopicArn=self.topic_arn, Subject=subject, Message=body)
            except Exception:
                log.exception("Failed to send the completion notification")
        return locations

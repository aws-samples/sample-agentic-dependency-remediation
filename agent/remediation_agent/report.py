"""Builds result.json and report.md for a run."""

from __future__ import annotations

STATUS_TEXT = {
    "FIXED": "All vulnerable dependencies were upgraded and the build passed.",
    "PARTIAL_FIX": "Some vulnerable dependencies were upgraded and the build passed. Others need a developer.",
    "NO_VULNERABILITIES": "No known vulnerabilities were found in the declared dependencies.",
    "NOT_FIXED": "The agent could not produce a verified fix.",
    "BUDGET_EXHAUSTED": "The build attempt budget ran out before the build passed.",
    "INCOMPLETE": "The agent ended without submitting a fix.",
    "ERROR": "The run failed with an error.",
}


MAX_LISTED_ADVISORIES = 6


def advisory_summary(advisories: list[str]) -> str:
    """'N advisories: A, B, C (+M more)'. The count always matches the full list."""
    if not advisories:
        return "none"
    shown = ", ".join(advisories[:MAX_LISTED_ADVISORIES])
    more = len(advisories) - MAX_LISTED_ADVISORIES
    noun = "advisory" if len(advisories) == 1 else "advisories"
    return f"{len(advisories)} {noun}: {shown}" + (f" (+{more} more)" if more > 0 else "")


def build_result(task, ecosystem: str | None, state, outcome_extra: dict) -> dict:
    fixes = list(state.packages.values())
    return {
        "run_id": task.run_id,
        "project": task.project,
        "ecosystem": ecosystem,
        "app_dir": task.app_dir,
        "status": state.status,
        "reason": state.reason,
        "fixed": [{"package": f.package, "from": f.from_version, "to": f.to_version, "advisories": f.advisories} for f in fixes if f.status == "UPDATED"],
        "skipped": [{"package": f.package, "from": f.from_version, "status": f.status, "note": f.note, "advisories": f.advisories}
                    for f in fixes if f.status != "UPDATED"],
        "build_attempts": state.attempts,
        "build_id": state.last_build.build_id if state.last_build else None,
        **outcome_extra,
    }


def build_report(result: dict, change_summary: str, patch: str | None, build_log_tail: str | None) -> str:
    status = result["status"]
    lines = [
        f"## Dependency remediation: {result['project']}",
        "",
        f"**Status:** {status}. {STATUS_TEXT.get(status, '')}",
        "",
    ]
    if result.get("reason"):
        lines += [f"**Reason:** {result['reason']}", ""]
    if result["fixed"]:
        lines += ["### Upgraded", "", "| Package | From | To | Advisories |", "|---|---|---|---|"]
        lines += [f"| `{f['package']}` | {f['from']} | {f['to']} | {advisory_summary(f['advisories'])} |" for f in result["fixed"]]
        lines.append("")
    if result["skipped"]:
        lines += ["### Not fixed", "", "| Package | Version | Why | Advisories |", "|---|---|---|---|"]
        lines += [f"| `{s['package']}` | {s['from']} | {s['note'] or s['status']} | {advisory_summary(s['advisories'])} |" for s in result["skipped"]]
        lines.append("")
    if change_summary:
        lines += ["### Code changes", "", change_summary, ""]
    if patch:
        lines += [
            "### Verification",
            "",
            f"- Dependencies installed, lockfiles regenerated, and unit tests passed on build attempt {result['build_attempts']}.",
            f"- Changed files: {', '.join(f'`{f}`' for f in result.get('changed_files', []))}",
            "",
            "Apply the patch from the repository root:",
            "",
            "```bash",
            "git apply --index fix.patch",
            "```",
            "",
        ]
    elif build_log_tail:
        lines += ["### Last build log", "", "```text", build_log_tail[-3000:], "```", ""]
    lines += [
        "> Generated by an AI agent. Review it as you would any other contribution.",
        "",
        f"<sub>Run ID: {result['run_id']} · tokens {result.get('input_tokens', 0)}+{result.get('output_tokens', 0)}</sub>",
    ]
    return "\n".join(lines)
